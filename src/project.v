module tt_um_vga_example (
    input  wire [7:0] ui_in,    
    output wire [7:0] uo_out,   
    input  wire [7:0] uio_in,   
    output wire [7:0] uio_out,  
    output wire [7:0] uio_oe,   
    input  wire       ena,      
    input  wire       clk,      
    input  wire       rst_n     
);
    wire _unused_ok = &{ena, ui_in, uio_in, 1'b0, rst_n};
    assign uio_out = 8'd0;
    assign uio_oe  = 8'd0;

    wire hsync_raw, vsync_raw, video_active_raw;
    wire [9:0] pix_x;
    wire [9:0] pix_y;

    hvsync_generator vga_sync_gen (
        .clk(clk),
        .reset(1'b0), 
        .hsync(hsync_raw),
        .vsync(vsync_raw),
        .display_on(video_active_raw),
        .hpos(pix_x),
        .vpos(pix_y)
    );

    // Centered 512x256 display window (keeps clean 2:1 pixel scaling)
    wire [9:0] start_x = 10'd64; 
    wire [9:0] start_y = 10'd112; 
    wire in_window_raw = (pix_x >= start_x && pix_x < (start_x + 10'd512)) &&
                         (pix_y >= start_y && pix_y < (start_y + 10'd256));

    // Downscale coordinates: 512/32 = 16x horizontal scale (>> 4)
    //                       256/16 = 16x vertical scale   (>> 4)
    wire [9:0] diff_x = pix_x - start_x;
    wire [9:0] diff_y = pix_y - start_y;
    wire [4:0] vid_x  = (pix_x >= start_x) ? diff_x[8:4] : 5'd0;
    wire [3:0] vid_y  = (pix_y >= start_y) ? diff_y[7:4] : 4'd0;

    // 60 frames animation (~960 words)
    parameter TOTAL_FRAMES = 6'd60; 
    reg [3:0] refresh_divider; 
    reg [5:0] frame_counter;
    reg last_vsync;

    initial begin
        frame_counter   = 6'd0; 
        refresh_divider = 4'd0;
        last_vsync      = 1'b0;
    end

    // 60 Hz / 10 = 6 FPS playback (runs 10 seconds total)
    always @(posedge clk) begin
        last_vsync <= vsync_raw;
        if (last_vsync && !vsync_raw) begin
            if (refresh_divider == 4'd9) begin
                refresh_divider <= 4'd0;
                frame_counter   <= (frame_counter >= TOTAL_FRAMES - 6'd1) ? 6'd0 : frame_counter + 6'd1;
            end else begin
                refresh_divider <= refresh_divider + 4'd1;
            end
        end
    end

    wire pixel_value;
    video_rom my_rom (
        .clk(clk),
        .frame(frame_counter),
        .x(vid_x),
        .y(vid_y),
        .pixel(pixel_value)
    );

    // 2-Cycle pipeline to match synchronous Block RAM latency and meet 25.18 MHz timing
    reg pipe1_active, pipe2_active;
    reg pipe1_window, pipe2_window;
    reg pipe1_hsync,  pipe2_hsync;
    reg pipe1_vsync,  pipe2_vsync;

    always @(posedge clk) begin
        pipe1_active <= video_active_raw;
        pipe1_window <= in_window_raw;
        pipe1_hsync  <= hsync_raw;
        pipe1_vsync  <= vsync_raw;

        pipe2_active <= pipe1_active;
        pipe2_window <= pipe1_window;
        pipe2_hsync  <= pipe1_hsync;
        pipe2_vsync  <= pipe1_vsync;
    end

    // Monochrome pixel output
    reg [1:0] R, G, B;
    always @(posedge clk) begin
        if (pipe2_active && pipe2_window && pixel_value) begin
            R <= 2'b11;
            G <= 2'b11;
            B <= 2'b11;
        end else begin
            R <= 2'b00;
            G <= 2'b00;
            B <= 2'b00;
        end
    end

    // Tiny Tapeout VGA pinout: {hsync, B0, G0, R0, vsync, B1, G1, R1}
    assign uo_out = {pipe2_hsync, B[0], G[0], R[0], pipe2_vsync, B[1], G[1], R[1]};

endmodule

module hvsync_generator (
    input  wire       clk,
    input  wire       reset,
    output reg        hsync,
    output reg        vsync,
    output wire       display_on,
    output reg  [9:0] hpos,
    output reg  [9:0] vpos
);
    parameter H_DISPLAY    = 640;
    parameter H_FRONT      = 16;
    parameter H_SYNC       = 96;
    parameter H_BACK       = 48;
    parameter V_DISPLAY    = 480;
    parameter V_BOTTOM     = 10;
    parameter V_SYNC       = 2;
    parameter V_TOP        = 33;
    parameter H_SYNC_START = H_DISPLAY + H_FRONT;
    parameter H_SYNC_END   = H_DISPLAY + H_FRONT + H_SYNC - 1;
    parameter H_MAX        = H_DISPLAY + H_FRONT + H_SYNC + H_BACK - 1;
    parameter V_SYNC_START = V_DISPLAY + V_BOTTOM;
    parameter V_SYNC_END   = V_DISPLAY + V_BOTTOM + V_SYNC - 1;
    parameter V_MAX        = V_DISPLAY + V_BOTTOM + V_SYNC + V_TOP - 1;

    wire hmaxxed = (hpos == H_MAX) || reset;
    wire vmaxxed = (vpos == V_MAX) || reset;

    always @(posedge clk) begin
        hsync <= ~(hpos >= H_SYNC_START && hpos <= H_SYNC_END);
        if (hmaxxed) hpos <= 10'd0;
        else hpos <= hpos + 10'd1;
    end

    always @(posedge clk) begin
        vsync <= ~(vpos >= V_SYNC_START && vpos <= V_SYNC_END);
        if (hmaxxed) begin
            if (vmaxxed) vpos <= 10'd0;
            else vpos <= vpos + 10'd1;
        end
    end

    assign display_on = (hpos < H_DISPLAY) && (vpos < V_DISPLAY);
endmodule

